import { v7 as uuidv7 } from 'uuid';

// ID створює клієнт, не база — наскрізне рішення проєкту (корінь CLAUDE.md).
// v7, а не v4: перші 48 біт це мітка часу, тож ключі зростають, і вставка
// не розкидає їх по всьому індексу. Дефолт uuidv7() у Postgres спрацює
// тільки якщо значення не передали — тут ми передаємо своє.
export const newId = (): string => uuidv7();
