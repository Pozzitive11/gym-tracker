-- 2. Назви вправ із наявних програм, яких нема в системному каталозі, стають
-- «моїми» вправами власника програми. DISTINCT ON схлопує дублі: «жим» і
-- «Жим » в одного юзера — одна вправа (узгоджено з унікальним індексом по
-- lower(name)).
INSERT INTO "exercises" ("user_id", "name")
SELECT DISTINCT ON (p."user_id", lower(trim(de."name")))
  p."user_id",
  trim(de."name")
FROM "day_exercises" de
JOIN "program_days" pd ON pd."id" = de."day_id"
JOIN "programs" p ON p."id" = pd."program_id"
WHERE NOT EXISTS (
  SELECT 1 FROM "exercises" e
  WHERE e."user_id" IS NULL AND lower(e."name") = lower(trim(de."name"))
)
ORDER BY p."user_id", lower(trim(de."name")), trim(de."name");
--> statement-breakpoint

-- 3. Кожна вправа програми отримує посилання на каталог: системну, якщо
-- назва збіглась, інакше щойно створену «мою» вправу власника.
UPDATE "day_exercises" de
SET "exercise_id" = e."id"
FROM "program_days" pd, "programs" p, "exercises" e
WHERE pd."id" = de."day_id"
  AND p."id" = pd."program_id"
  AND lower(e."name") = lower(trim(de."name"))
  AND (e."user_id" IS NULL OR e."user_id" = p."user_id");
